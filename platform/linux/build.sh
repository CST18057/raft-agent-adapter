#!/usr/bin/env bash
# Build the Linux stdio launcher (bin/grok) for this checkout.
# Records the resolved Node executable so the launcher is immune to PATH
# changes, mirroring what platform/windows/Build.ps1 writes to
# .local/node-path.txt.
set -euo pipefail

ROOT=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/../.." && pwd -P)

NODE_CMD=${NODE:-node}
if ! command -v "$NODE_CMD" >/dev/null 2>&1; then
  echo "Node.js was not found on PATH. Install Node.js 22 or newer first." >&2
  exit 1
fi
NODE_EXE=$("$NODE_CMD" -p "require('node:fs').realpathSync(process.execPath)")
NODE_MAJOR=$("$NODE_EXE" -p "process.versions.node.split('.')[0]")
if [ "$NODE_MAJOR" -lt 22 ]; then
  echo "Node.js 22 or newer is required (found $("$NODE_EXE" --version))." >&2
  exit 1
fi

mkdir -p "$ROOT/bin" "$ROOT/.local"
printf '%s' "$NODE_EXE" > "$ROOT/.local/node-path.txt"

# The launcher exec()s node directly so it *becomes* the adapter process.
# This matters: Raft spawns runtime children in their own process group on
# POSIX and signals the launcher PID when shutting down or probing. With
# exec, the signal reaches the adapter and its Devin child; a wrapping
# script would leave orphaned processes behind.
cat > "$ROOT/bin/grok" <<'EOF'
#!/bin/sh
# Generated by platform/linux/build.sh - do not edit.
set -eu
self=$0
while [ -h "$self" ]; do
  dir=$(CDPATH= cd -- "$(dirname -- "$self")" && pwd -P)
  self=$(readlink "$self")
  case $self in /*) ;; *) self=$dir/$self ;; esac
done
root=$(CDPATH= cd -- "$(dirname -- "$self")/.." && pwd -P)
node=$(cat "$root/.local/node-path.txt")
exec "$node" "$root/src/adapter.mjs" "$@"
EOF
chmod +x "$ROOT/bin/grok"

"$ROOT/bin/grok" --version >/dev/null || { echo "Launcher version check failed." >&2; exit 1; }
"$ROOT/bin/grok" --version
